# 6.	Даны действительные числа a, b, c, d. Если a < b < c < d,  то  каждое число заменить наибольшим из них;  
# если a > b > c >  d, то числа оставить без изменения; иначе все числа заменяются их квадратами

a, b, c, d = map(float, input("Введите четыре числа: ").split())

if a < b < c < d:
    max_val = max(a, b, c, d)
    a = b = c = d = max_val
elif a > b > c > d:
    pass
else:
    a, b, c, d = a**2, b**2, c**2, d**2

print(f"Результат: {a}, {b}, {c}, {d}")